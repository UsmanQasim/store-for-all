// Builds src/components/icon-paths.ts from @material-symbols/svg-400 (the icon set Stitch uses).
// Usage: node scripts/gen-icons.cjs   — edit NAMES to add icons.
const fs = require('fs');
const path = require('path');
const base = path.dirname(require.resolve('@material-symbols/svg-400/package.json')) + '/outlined/';

// Stitch uses Material Symbols font ligatures; a few are aliases of differently named SVGs.
const ALIAS = { camera_alt: 'photo_camera', chat_bubble_outline: 'chat_bubble', done: 'check', expand_more: 'keyboard_arrow_down', favorite_border: 'favorite', gshield: 'shield', help_outline: 'help', local_grocery_store: 'shopping_cart', local_offer: 'sell', phonelink_setup: 'mobile_gear', push_pin: 'keep' };
const NAMES = fs.readFileSync(path.join(__dirname, 'icon-names.txt'), 'utf8').split(/\s+/).filter(Boolean);

const read = (f) => (fs.existsSync(base + f) ? [...fs.readFileSync(base + f, 'utf8').matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ') : null);
const out = {};
for (const n of [...new Set(NAMES)].sort()) {
  const file = ALIAS[n] ?? n;
  const o = read(`${file}.svg`);
  if (!o) throw new Error(`Unknown Material Symbol: ${n}`);
  const f = read(`${file}-fill.svg`);
  out[n] = f && f !== o ? [o, f] : [o];
}
fs.writeFileSync(
  path.join(__dirname, '../src/components/icon-paths.ts'),
  `// GENERATED by scripts/gen-icons.cjs — do not edit. [outline, fill?] paths, viewBox "0 -960 960 960".\nexport const ICONS = ${JSON.stringify(out)} as const;\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${Object.keys(out).length} icons`);
