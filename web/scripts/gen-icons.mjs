// Builds src/components/icon-paths.ts (Material Symbols, the set Stitch uses) from the icons the code references.
// Picks up <Icon name="x" …/> literals automatically; list names chosen at runtime in scripts/icon-extra.txt.
// Runs automatically before `dev` and `build`.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(import.meta.dirname, '..');
const base = path.dirname(createRequire(import.meta.url).resolve('@material-symbols/svg-400/package.json')) + '/outlined/';
const ALIAS = { expand_more: 'keyboard_arrow_down', local_grocery_store: 'shopping_cart', phonelink_setup: 'mobile_gear', help_outline: 'help' };

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const names = new Set(fs.readFileSync(path.join(root, 'scripts/icon-extra.txt'), 'utf8').split(/\s+/).filter(Boolean));
for (const f of walk(path.join(root, 'src')).filter((f) => /\.tsx?$/.test(f) && !f.endsWith('icon-paths.ts'))) {
  for (const m of fs.readFileSync(f, 'utf8').matchAll(/<Icon\b[^>]*?\bname="([a-z0-9_]+)"/g)) names.add(m[1]);
}
const read = (f) => (fs.existsSync(base + f) ? [...fs.readFileSync(base + f, 'utf8').matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ') : null);
const out = {};
for (const n of [...names].sort()) {
  const file = ALIAS[n] ?? n;
  const o = read(`${file}.svg`);
  if (!o) throw new Error(`Unknown Material Symbol: ${n}`);
  const fill = read(`${file}-fill.svg`);
  out[n] = fill && fill !== o ? [o, fill] : [o];
}
fs.writeFileSync(
  path.join(root, 'src/components/icon-paths.ts'),
  `// GENERATED by scripts/gen-icons.mjs — do not edit. [outline, fill?] paths, viewBox "0 -960 960 960".\nexport const ICONS: Record<string, readonly string[]> = ${JSON.stringify(out)};\n`,
);
console.log(`icons: ${Object.keys(out).length}`);
